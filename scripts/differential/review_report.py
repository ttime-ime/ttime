#!/usr/bin/env python3
"""Generate docs/review/disagreements.md: every fixture input on which T-Time,
pyewts and ewts-rs do not all agree, for manual review by an expert.

Usage (repository root, after `cargo build -p ttime-cli`, with pyewts installed):
    .venv/bin/python scripts/differential/review_report.py

It runs scripts/differential/ewts-rs-diff itself. Nothing here says who is right.
"""
import glob
import os
import re
import subprocess
import pyewts

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CLI = os.path.join(ROOT, "target", "debug", "ttime-cli")
FIX = os.path.join(ROOT, "crates/ttime-core/tests/fixtures")
conv = pyewts.pyewts()

# ewts-rs prints Rust Debug strings for inputs; match on that spelling.
run = subprocess.run(["cargo", "run", "-q", "--release"], cwd=os.path.join(ROOT, "scripts/differential/ewts-rs-diff"),
                     capture_output=True, text=True, encoding="utf8")
er, cur = {}, None
for line in run.stdout.split("\n"):
    m = re.match(r'^(\S+\.tsv)\t(".*")$', line)
    if m:
        cur = (m.group(1), m.group(2))
        continue
    m = re.match(r"^   ewts (.*)$", line)
    if m and cur:
        er[cur] = m.group(1).strip()


def debug(s):  # Rust {:?} for the characters that occur in fixtures
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def esc(s):
    return " ".join("%04X" % ord(x) for x in s)


def ours(t):
    return subprocess.run([CLI], input=t + "\n", capture_output=True, text=True, encoding="utf8").stdout.rstrip("\n")


def theirs(t):
    try:
        return esc(conv.toUnicode(t))
    except Exception as e:
        return "(raised %s)" % type(e).__name__


def glyphs(hexs):
    try:
        t = "".join(chr(int(h, 16)) for h in hexs.split())
        return "".join(c if c.isprintable() and c not in "`|" else "." for c in t)
    except ValueError:
        return ""


sections = {}
total = 0
for f in sorted(glob.glob(FIX + "/*.tsv")):
    name = os.path.basename(f)
    if name == "precomposed.tsv":
        continue
    for line in open(f, encoding="utf8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#") or "\t" not in line:
            continue
        inp = line.split("\t")[0]
        total += 1
        o, p = esc(ours(inp)), theirs(inp)
        e = er.get((name, debug(inp)), o)  # absent from ewts-rs-diff output = same as T-Time
        if not (o == p == e):
            sections.setdefault(name, []).append((inp, o, p, e))

out = ["# Fixture disagreements between T-Time, pyewts and ewts-rs", "",
       f"Generated by `scripts/differential/review_report.py`. {total} fixture inputs compared; "
       f"{sum(map(len, sections.values()))} differ. Code points are hexadecimal; the glyph column is "
       "T-Time's output. **Nothing here says which implementation is right.** "
       "Expert triage is in `expert-review.md`.", ""]
for name, rows in sections.items():
    out += [f"## {name} ({len(rows)})", "", "| Input | T-Time | pyewts | ewts-rs |", "|---|---|---|---|"]
    for inp, o, p, e in rows:
        cell = lambda v, ref: "same" if v == ref else f"`{v}`"
        shown = inp.replace("|", "\\|").replace("`", "'")
        out.append(f"| `{shown}` | `{o}` {glyphs(o)} | {cell(p, o)} | {cell(e, o)} |")
    out.append("")
open(os.path.join(ROOT, "docs/review/disagreements.md"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(total, "inputs;", {k: len(v) for k, v in sections.items()})
