#!/usr/bin/env python3
"""Regenerate crates/ttime-core/tests/fixtures/stacks.tsv.

Expected values are computed from code points here, not from the Rust tables,
so the fixture is an independent check of the converter's stack output.
"""
import pathlib

BASE = {
    "k": 0x0F40, "kh": 0x0F41, "g": 0x0F42, "ng": 0x0F44, "c": 0x0F45, "j": 0x0F47,
    "ny": 0x0F49, "t": 0x0F4F, "th": 0x0F50, "d": 0x0F51, "n": 0x0F53, "p": 0x0F54,
    "ph": 0x0F55, "b": 0x0F56, "m": 0x0F58, "ts": 0x0F59, "tsh": 0x0F5A, "dz": 0x0F5B,
    "w": 0x0F5D, "zh": 0x0F5E, "z": 0x0F5F, "y": 0x0F61, "r": 0x0F62, "l": 0x0F63,
    "sh": 0x0F64, "s": 0x0F66, "h": 0x0F67,
}

STACKS = """rk rg rng rj rny rt rd rn rb rm rts rdz
lk lg lng lc lj lt ld lp lb lh
sk sg sng sny st sd sn sp sb sm
ky khy gy py phy by my
kr khr gr tr thr dr pr phr br mr shr sr hr
kl gl bl zl rl sl
kw khw gw cw nyw tw dw tsw tshw zhw zw rw shw sw hw
rky rgy rmy sky sgy spy sby smy skr sgr spr sbr smr
grw drw rgw rtsw""".split()


def top(k):
    return chr(BASE[k])


def sub(k):
    return chr(BASE[k] - 0x0F40 + 0x0F90)


def split(s):
    keys = sorted(BASE, key=len, reverse=True)
    out = []
    while s:
        k = next(k for k in keys if s.startswith(k))
        out.append(k)
        s = s[len(k):]
    return out


lines = ["# Generated by scripts/gen_stack_fixture.py from code points; do not edit."]
for st in STACKS:
    ks = split(st)
    lines.append(f"{st}a\t{top(ks[0])}{''.join(sub(k) for k in ks[1:])}")
# Not derivable from the general rules.
lines.append(f"snra\t{top('s')}{sub('n')}{sub('r')}")
lines.append(f"phywa\t{top('ph')}{sub('y')}{sub('w')}")

out = pathlib.Path(__file__).resolve().parent.parent / "crates/ttime-core/tests/fixtures/stacks.tsv"
out.write_text("\n".join(lines) + "\n", encoding="utf8")
print(f"wrote {len(lines) - 1} stacks to {out}")
